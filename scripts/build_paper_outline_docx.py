def body(doc, text, indent=True, size=10.5, bold=False, color=None, space_after=3):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.3
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    set_font(p.add_run(text), "宋体", size, bold, color)
    return p


